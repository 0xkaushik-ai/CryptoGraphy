package aes

import "math/bits"

// sbox and invsbox are the AES S-box and inverse S-box, respectively. They are computed from the Galois field GF(2^8) using the multiplicative inverse and an affine transformation.
// sbox is used during subbytes during encryption
// invbox is used during decryption during invsubbytes

// this is the AES S-box and inverse S-box
var (
	sbox    [256]byte
	invSbox [256]byte
)

// init build the both the tables once, when the package is loaded

func init() {
	for i := 0; i < 256; i++ {
		s := affineTransform(gfInverse(byte(i)))
		sbox[i] = s
		invSbox[s] = byte(i) // the inverse table is just the reverse mapping
	}
}

func affineTransform(b byte) byte {
	// The affine transformation is defined by the following matrix multiplication and addition in GF(2):
	// [1 0 0 0 1 1 1 1]   [x0]   [y0]
	// [1 1 0 0 0 1 1 1]   [x1]   [y1]
	// [1 1 1 0 0 0 1 1] * [x2] = [y2]
	// [1 1 1 1 0 0 0 1]   [x3]   [y3]
	// [1 1 1 1 1 0 0 0]   [x4]   [y4]
	// [0 1 1 1 1 1 0 0]   [x5]   [y5]
	// [0 0 1 1 1 1 1 0]   [x6]   [y6]
	// [0 0 0 1 1 1 1 1]   [x7]   [y7]
	// and then adding the constant vector [0x63] (which is [01100011] in binary).
	// This can be implemented efficiently using bitwise operations.

	return b ^ bits.RotateLeft8(b, 1) ^
		bits.RotateLeft8(b, 2) ^
		bits.RotateLeft8(b, 3) ^
		bits.RotateLeft8(b, 4) ^
		0x63
}

// this whole file is about the S-box and inverse S-box, which are used in the AES encryption and decryption process. The S-box is a non-linear substitution table that provides confusion in the cipher, while the inverse S-box is used to reverse this substitution during decryption. The S-box is generated by taking the multiplicative inverse in GF(2^8) and then applying an affine transformation. The inverse S-box is simply the reverse mapping of the S-box.
// here we have  two function whoes jobs are to generate the S-box and inverse S-box, and a helper function to perform the affine transformation. The S-box is generated by iterating over all possible byte values (0-255), computing their multiplicative inverse in GF(2^8), applying the affine transformation, and storing the result in the S-box. The inverse S-box is generated by reversing this mapping.
